function typeWriter(containerId, text, buttonContainerId) {
  const container = document.getElementById(containerId);
  const btn = document.getElementById(buttonContainerId)
  if (!container) return;
  container.textContent = "";
  if(btn) btn.classList.add("opacity-0");

  const lines = text.split("\n");
  let currentLine = 0;

  function printLine() {
    if (currentLine < lines.length) {
      container.textContent += lines[currentLine] + "\n";
      currentLine++;
      setTimeout(printLine, 45);
    } else if (btn) {
      btn.classList.remove("opacity-0");
    }
  }
  printLine();
}